package com.openfolio.core.utils

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import java.math.BigDecimal

class CasStatementParserTest {

    private lateinit var parser: CasStatementParser

    @Before
    fun setUp() {
        parser = CasStatementParser()
    }

    @Test
    fun isCasStatementDetectsValidCamsAndKfintechStatements() {
        val camsSample = """
            Consolidated Account Statement
            CAMS Investor Services
            Folio No: 1234567/89
            01-Jan-2024 Purchase - Normal 5,000.00 120.450 41.5110 120.450
        """.trimIndent()

        assertTrue(parser.isCasStatement(camsSample))

        val nonCasSample = """
            Broker Contract Note
            Trade Date: 2024-01-01
            Security: RELIANCE
            Qty: 10 Price: 2500
        """.trimIndent()

        assertFalse(parser.isCasStatement(nonCasSample))
        assertFalse(parser.isCasStatement(""))
    }

    @Test
    fun parseExtractsTransactionsWithAmcSchemeAndIsin() {
        val rawText = """
            Consolidated Account Statement
            Generated by CAMS
            
            HDFC Mutual Fund
            Folio No: 9876543/21
            HDFC Top 100 Fund - Growth Option ISIN: INF179K01BE2
            Registrar: CAMS
            
            Date Transaction Amount Units Price Balance
            Opening Unit Balance: 0.000
            01-Jan-2024 Systematic Investment Plan 5,000.00 50.123 99.7540 50.123
            Stamp Duty: 0.25
            15-Jan-2024 SIP Purchase 5,000.00 49.500 101.0100 99.623
            05-Feb-2024 Redemption (4,000.00) (38.000) 105.2630 61.623
            STT Paid: 1.00
            20-Feb-2024 IDCW Payout 500.00 0.000 106.0000 61.623
            Closing Unit Balance: 61.623
            *** End of Statement ***
        """.trimIndent()

        val drafts = parser.parse(rawText, "doc_cams_1")

        assertEquals(4, drafts.size)

        // 1. First SIP
        val d1 = drafts[0]
        assertEquals("doc_cams_1", d1.documentId)
        assertEquals("HDFC Top 100 Fund - Growth Option", d1.assetName)
        assertEquals("BUY", d1.transactionType)
        assertEquals("5000.00", d1.netAmount)
        assertEquals("50.123", d1.quantity)
        assertEquals("99.7540", d1.price)
        assertEquals(98, d1.confidence)
        assertEquals(true, d1.isAccepted)
        assertEquals(false, d1.isManual)
        assertEquals("MUTUAL_FUND", d1.assetClass)
        assertEquals("CAMS/KFintech", d1.broker)
        assertEquals("INF179K01BE2", d1.isin)
        assertNotNull(d1.tradeDate)

        // 2. Second SIP Purchase
        val d2 = drafts[1]
        assertEquals("BUY", d2.transactionType)
        assertEquals("5000.00", d2.netAmount)
        assertEquals("49.500", d2.quantity)
        assertEquals("101.0100", d2.price)

        // 3. Redemption (negative amount & units in parens)
        val d3 = drafts[2]
        assertEquals("SELL", d3.transactionType)
        assertEquals("4000.00", d3.netAmount)
        assertEquals("38.000", d3.quantity)
        assertEquals("105.2630", d3.price)

        // 4. IDCW Payout
        val d4 = drafts[3]
        assertEquals("DIVIDEND", d4.transactionType)
        assertEquals("500.00", d4.netAmount)
        assertEquals("0.000", d4.quantity)
    }

    @Test
    fun parseHandlesMultipleAmcsAndSchemes() {
        val rawText = """
            Consolidated Account Statement
            KFin Technologies Limited
            
            SBI Mutual Fund
            Folio No: 111111/22
            SBI Large & Midcap Fund - Direct Plan - Growth (ISIN: INF200K01TL6)
            01-Jan-2024 Purchase - Normal 10,000.00 120.450 83.0220 120.450
            
            Parag Parikh Mutual Fund
            Folio No: 333333/44
            101 - Parag Parikh Flexi Cap Fund - Direct Plan - Growth (Advisor: DIRECT) ISIN: INF879O01019
            10-Jan-2024 Systematic Investment 2,500.00 35.714 70.0000 35.714
        """.trimIndent()

        val drafts = parser.parse(rawText, "doc_multi_amc")

        assertEquals(2, drafts.size)

        assertEquals("SBI Large & Midcap Fund - Direct Plan - Growth", drafts[0].assetName)
        assertEquals("INF200K01TL6", drafts[0].isin)
        assertEquals("10000.00", drafts[0].netAmount)
        assertEquals("120.450", drafts[0].quantity)

        assertEquals("Parag Parikh Flexi Cap Fund - Direct Plan - Growth", drafts[1].assetName)
        assertEquals("INF879O01019", drafts[1].isin)
        assertEquals("2500.00", drafts[1].netAmount)
        assertEquals("35.714", drafts[1].quantity)
    }

    @Test
    fun parseIgnoresNonTransactionNoiseLines() {
        val rawText = """
            Consolidated Account Statement
            CAMS
            Nippon India Mutual Fund
            Nippon India Small Cap Fund - Growth ISIN: INF204K01W16
            
            Page 1 of 5
            Opening Unit Balance: 100.000
            Stamp Duty: ₹ 0.50
            STT Paid: ₹ 12.00
            Address Updated on 12-Jan-2024
            Total Cost Value: 50,000.00
            Total Market Value: 75,000.00
            Closing Unit Balance: 150.000
            
            15-Jan-2024 Additional Purchase 5,000.00 50.000 100.0000 150.000
        """.trimIndent()

        val drafts = parser.parse(rawText, "doc_noise")

        assertEquals(1, drafts.size)
        assertEquals("BUY", drafts[0].transactionType)
        assertEquals("5000.00", drafts[0].netAmount)
        assertEquals("50.000", drafts[0].quantity)
    }

    @Test
    fun parseHandlesDiverseDateFormatsAndThreeNumericColumns() {
        val rawText = """
            Consolidated Account Statement
            Registrar: Computer Age Management Services
            Mirae Asset Large Cap Fund - Direct Plan - Growth ISIN: INF769K01134
            
            12/03/2024 Purchase - Normal 3,000.00 30.000 100.0000
            15-04-2024 SIP Purchase 2,500.00 24.510 102.0000 54.510
            2024-05-18 Redemption (1,500.00) (14.285) 105.0000 40.225
            01-Jun-24 Systematic Investment 4,000.00 36.363 110.0000
        """.trimIndent()

        val drafts = parser.parse(rawText, "doc_dates")

        assertEquals(4, drafts.size)
        assertEquals("BUY", drafts[0].transactionType)
        assertEquals("3000.00", drafts[0].netAmount)
        assertEquals("30.000", drafts[0].quantity)
        assertEquals("100.0000", drafts[0].price)

        assertEquals("BUY", drafts[1].transactionType)
        assertEquals("2500.00", drafts[1].netAmount)
        assertEquals("24.510", drafts[1].quantity)

        assertEquals("SELL", drafts[2].transactionType)
        assertEquals("1500.00", drafts[2].netAmount)
        assertEquals("14.285", drafts[2].quantity)

        assertEquals("BUY", drafts[3].transactionType)
        assertEquals("4000.00", drafts[3].netAmount)
        assertEquals("36.363", drafts[3].quantity)
    }

    @Test
    fun parseHandlesDirectAmcStatementOfAccount() {
        val rawText = """
            STATEMENT OF ACCOUNT
            UTI Mutual Fund
            Folio Number: 50123456789
            UTI Nifty 50 Index Fund - Direct Plan - Growth Option
            ISIN: INF789F01AX7
            
            Date Transaction Amount Units Price Balance
            10-Feb-2024 Systematic Investment Plan 5,000.00 35.123 142.3500 35.123
        """.trimIndent()

        assertTrue(parser.isCasStatement(rawText))
        val drafts = parser.parse(rawText, "doc_amc_direct")

        assertEquals(1, drafts.size)
        assertEquals("UTI Nifty 50 Index Fund - Direct Plan - Growth Option", drafts[0].assetName)
        assertEquals("INF789F01AX7", drafts[0].isin)
        assertEquals("BUY", drafts[0].transactionType)
        assertEquals("5000.00", drafts[0].netAmount)
        assertEquals("35.123", drafts[0].quantity)
        assertEquals("142.3500", drafts[0].price)
    }

    @Test
    fun parseHandlesWrappedMultiLineDescriptions() {
        val rawText = """
            Consolidated Account Statement
            CAMS
            Folio No: 123456/78
            Quant Active Fund - Growth Option - Direct Plan (ISIN: INF966L01AA3)
            
            15-Jan-2024
            Systematic Investment Plan (SIP)
            via Net Banking
            10,000.00 15.234 656.4264 15.234
        """.trimIndent()

        val drafts = parser.parse(rawText, "doc_multiline")

        assertEquals(1, drafts.size)
        assertEquals("Quant Active Fund - Growth Option - Direct Plan", drafts[0].assetName)
        assertEquals("INF966L01AA3", drafts[0].isin)
        assertEquals("BUY", drafts[0].transactionType)
        assertEquals("10000.00", drafts[0].netAmount)
        assertEquals("15.234", drafts[0].quantity)
    }
}
