package com.openfolio.core.utils

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class CasStatementParserStreamingTest {

    private val parser = CasStatementParser()

    @Test
    fun parsePagePreservesAmcSchemeAndIsinAcross50Pages() {
        val state = CasParseState()
        val allDrafts = mutableListOf<com.openfolio.core.data.local.entity.DraftTransactionEntity>()
        val pages = mutableListOf<String>()

        for (page in 1..50) {
            val pageText = buildString {
                if (page == 1) {
                    appendLine("Consolidated Account Statement")
                    appendLine("Generated by CAMS")
                    appendLine("HDFC Mutual Fund")
                    appendLine("Folio No: 1234567/89")
                    appendLine("HDFC Top 100 Fund - Direct Plan - Growth ISIN: INF179K01BE2")
                } else if (page == 26) {
                    appendLine("Parag Parikh Mutual Fund")
                    appendLine("Folio No: 9988776/55")
                    appendLine("Parag Parikh Flexi Cap Fund - Direct Plan - Growth ISIN: INF879O01019")
                }
                appendLine("Page $page of 50")
                val day = ((page - 1) % 28) + 1
                val dayStr = day.toString().padStart(2, '0')
                appendLine("$dayStr-Jan-2024 Systematic Investment Plan 5,000.00 49.8753 100.2500 100.000")
                if (page % 5 == 0) {
                    appendLine("Stamp Duty: 0.25")
                    appendLine("$dayStr-Feb-2024 Redemption (2,500.00) (24.000) 104.1667 76.000")
                }
            }
            pages.add(pageText)
            allDrafts.addAll(parser.parsePage(pageText, page, "doc-cas-50", state))
        }

        // 50 SIP purchases + 10 redemptions (every 5th page)
        assertEquals(60, allDrafts.size)
        assertTrue(state.hasSeenCasSignal)

        val page10Draft = allDrafts.first { it.sourcePage == 10 }
        assertEquals("HDFC Top 100 Fund - Direct Plan - Growth", page10Draft.assetName)
        assertEquals("INF179K01BE2", page10Draft.isin)
        assertEquals("BUY", page10Draft.transactionType)
        assertEquals("49.8753", page10Draft.quantity)
        assertEquals("100.2500", page10Draft.price)
        assertEquals("5000.00", page10Draft.netAmount)

        val page40Drafts = allDrafts.filter { it.sourcePage == 40 }
        assertEquals(2, page40Drafts.size)
        assertTrue(page40Drafts.all { it.assetName == "Parag Parikh Flexi Cap Fund - Direct Plan - Growth" })
        assertTrue(page40Drafts.all { it.isin == "INF879O01019" })
        assertEquals("SELL", page40Drafts[1].transactionType)
        assertEquals("24.000", page40Drafts[1].quantity)

        // Compare against single-pass parse(rawText)
        val combinedDrafts = parser.parse(pages.joinToString("\n"), "doc-cas-50")
        assertEquals(allDrafts.size, combinedDrafts.size)
        assertEquals(allDrafts.map { it.assetName to it.netAmount }, combinedDrafts.map { it.assetName to it.netAmount })
    }
}
